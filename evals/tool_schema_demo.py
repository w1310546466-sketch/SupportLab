"""Teaching demo: distinguish declarations, proposed calls and actual tool results."""

import argparse
from datetime import datetime, timezone
from hashlib import sha256
import json
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory
from unittest.mock import patch

from supportlab.acceptance import report_reservation
from supportlab.contracts import model_tool_schemas
from supportlab.execution import ToolExecutor
from supportlab.storage import init_demo_db
from supportlab.tools import AppContext


def demonstrate():
    # These proposals are written by us, not generated by a live model.
    examples = [
        ("valid", "get_account_state", {"request_id": "req_demo_018"}, "ok", 1),
        ("missing_argument", "get_account_state", {}, "invalid_arguments", 0),
        ("extra_account", "get_account_state", {"request_id": "req_demo_018", "account_id": "acc_other"}, "invalid_arguments", 0),
        ("unregistered_tool", "reset_quota", {"request_id": "req_demo_018"}, "unknown_tool", 0),
        ("valid_but_absent", "get_account_state", {"request_id": "req_missing_001"}, "not_found", 1),
    ]
    rows = []
    with TemporaryDirectory(prefix="supportlab_schema_lesson_") as directory:
        db = Path(directory) / "demo.sqlite3"
        init_demo_db(db)
        before = sha256(db.read_bytes()).hexdigest()
        executor = ToolExecutor(AppContext("acc_demo"), db_path=db)
        for label, name, arguments, expected, expected_starts in examples:
            with patch("supportlab.execution.subprocess.run", wraps=subprocess.run) as worker:
                execution = executor.execute(name, arguments)
                starts = worker.call_count
            rows.append({"example": label, "proposed_call": {"name": name, "arguments": arguments},
                         "expected_status": expected, "tool_worker_starts": starts,
                         "passed": execution.result["status"] == expected and starts == expected_starts,
                         "result": execution.result})
        unchanged = before == sha256(db.read_bytes()).hexdigest()
    return {"created_at": datetime.now(timezone.utc).isoformat(), "version": "tool-schema-lesson-v1",
            "simulation": True, "execution_mode": "handwritten_proposals_real_local_executor",
            "model_api_calls": 0, "application_account": "acc_demo", "sources_unchanged": unchanged,
            "passed_examples": sum(row["passed"] for row in rows), "example_count": len(rows),
            "account_tool_schema": next(row for row in model_tool_schemas() if row["name"] == "get_account_state"),
            "examples": rows,
            "limitations": ["Proposals are handwritten; this does not measure model tool selection.",
                            "Parameter validation passing does not mean a record exists or a diagnosis is supported.",
                            "Uses a temporary business database; default data and conversation history are unchanged."]}


def main():
    parser = argparse.ArgumentParser(description="Offline tool declaration and execution lesson")
    parser.add_argument("--output", type=Path, required=True, help="New reports/*.json file; never overwritten")
    args = parser.parse_args()
    with report_reservation(args.output) as stream:
        report = demonstrate()
        json.dump(report, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    for row in report["examples"]:
        print(f"{row['example']}: {row['result']['status']}; tool_workers={row['tool_worker_starts']}")
    print(f"Examples: {report['passed_examples']}/{report['example_count']}; API=0; sources_unchanged={report['sources_unchanged']}")
    return 0 if report["passed_examples"] == report["example_count"] and report["sources_unchanged"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
